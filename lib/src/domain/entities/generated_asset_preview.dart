class GeneratedAssetPreview {
  const GeneratedAssetPreview({
    required this.id,
    required this.displayPath,
    required this.width,
    required this.height,
    required this.sizeBytes,
    required this.usesThumbnail,
  });

  final String id;
  final String displayPath;
  final int? width;
  final int? height;
  final int? sizeBytes;
  final bool usesThumbnail;
}
